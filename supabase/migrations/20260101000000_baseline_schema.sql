-- 9b. Helper functions (SECURITY DEFINER, search_path hardened)
--     Defined AFTER tables because SQL-language function bodies are validated
--     at CREATE time. set_updated_at() and is_project_director() are
--     intentionally NOT here (finance migration owns them via CREATE OR REPLACE).
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.handle_updated_at()
  RETURNS trigger
  LANGUAGE plpgsql
  SET search_path TO 'pg_catalog', 'pg_temp'
AS $$ BEGIN NEW.updated_at = now(); RETURN NEW; END; $$;

CREATE OR REPLACE FUNCTION public.user_profile_id(check_uid uuid)
  RETURNS bigint
  LANGUAGE sql
  STABLE SECURITY DEFINER
  SET search_path TO 'pg_catalog', 'pg_temp'
AS $$
  SELECT id FROM public.profiles WHERE uid = auth.uid() LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.current_user_role()
  RETURNS text
  LANGUAGE sql
  STABLE SECURITY DEFINER
  SET search_path TO 'pg_catalog', 'pg_temp'
AS $$
  SELECT role FROM public.profiles WHERE uid = auth.uid();
$$;

CREATE OR REPLACE FUNCTION public.is_director(check_uid uuid)
  RETURNS boolean
  LANGUAGE sql
  STABLE SECURITY DEFINER
  SET search_path TO 'pg_catalog', 'pg_temp'
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE uid = auth.uid() AND role = 'director'
  );
$$;

CREATE OR REPLACE FUNCTION public.is_project_member(_project_id bigint)
  RETURNS boolean
  LANGUAGE sql
  STABLE SECURITY DEFINER
  SET search_path TO 'pg_catalog', 'pg_temp'
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.project_members pm
    JOIN public.profiles p ON p.id = pm.profile_id
    WHERE pm.project_id = _project_id
      AND p.uid = auth.uid()
  );
$$;

CREATE OR REPLACE FUNCTION private.user_project_ids()
  RETURNS SETOF bigint
  LANGUAGE sql
  STABLE SECURITY DEFINER
  SET search_path TO 'pg_catalog', 'pg_temp'
AS $$
  SELECT pm.project_id
  FROM public.project_members pm
  WHERE pm.profile_id = public.user_profile_id(auth.uid());
$$;

-- Trigger functions for auto-linking directors to projects.
CREATE OR REPLACE FUNCTION public.auto_link_director_to_projects()
  RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'pg_catalog', 'pg_temp'
AS $$
BEGIN
  IF NEW.role = 'director' THEN
    INSERT INTO public.project_members (project_id, profile_id, role)
    SELECT p.id, NEW.id, 'director'
    FROM public.projects p
    ON CONFLICT DO NOTHING;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.auto_link_directors_to_new_project()
  RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'pg_catalog', 'pg_temp'
AS $$
BEGIN
  INSERT INTO public.project_members (project_id, profile_id, role)
  SELECT NEW.id, p.id, 'director'
  FROM public.profiles p
  WHERE p.role = 'director'
  ON CONFLICT DO NOTHING;

  IF NEW.created_by IS NOT NULL THEN
    INSERT INTO public.project_members (project_id, profile_id, role)
    VALUES (NEW.id, NEW.created_by, 'owner')
    ON CONFLICT DO NOTHING;
  END IF;

  RETURN NEW;
END;
$$;


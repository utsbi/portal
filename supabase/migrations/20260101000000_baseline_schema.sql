CREATE OR REPLACE FUNCTION public.mark_conversation_read(p_conversation_id bigint)
  RETURNS void
  LANGUAGE sql
AS $$
  INSERT INTO public.conversation_reads (conversation_id, profile_id, last_read_at)
  VALUES (p_conversation_id, public.user_profile_id(auth.uid()), now())
  ON CONFLICT (conversation_id, profile_id)
  DO UPDATE SET last_read_at = now();
$$;

CREATE OR REPLACE FUNCTION public.match_client_knowledge(
  _query_embedding public.vector,
  _match_count integer DEFAULT 5,
  _filter_uid uuid DEFAULT NULL::uuid,
  _similarity_threshold double precision DEFAULT 0.5
)
  RETURNS TABLE(id bigint, content text, metadata jsonb, similarity double precision)
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
AS $$
BEGIN
  RETURN QUERY
  SELECT ck.id, ck.content, ck.metadata,
    1 - (ck.embedding <=> _query_embedding) AS similarity
  FROM client_knowledge ck
  WHERE (_filter_uid IS NULL OR ck.uid = _filter_uid)
    AND 1 - (ck.embedding <=> _query_embedding) > _similarity_threshold
  ORDER BY ck.embedding <=> _query_embedding
  LIMIT _match_count;
END;
$$;


-- =====================================================================
-- BASELINE SCHEMA SNAPSHOT
-- =====================================================================
-- Reconstructed from the live `sbi` Supabase project (ref zxqwjnxrkzvygwdltuwi)
-- via read-only introspection. The live database was built by ~33 migrations
-- that were never checked into this repo; only the finance tables + 2 ALTERs
-- existed in VCS. This file captures everything that those finance migrations
-- depend on, so a clean `supabase db reset` applies in this order:
--
--   20260101000000_baseline_schema.sql        <- THIS FILE
--   20260526000000_create_finance_tables.sql  <- project_budgets/categories/
--                                                 transactions + set_updated_at()
--                                                 + is_project_director()
--   20260526000100_add_transaction_title.sql  <- ALTER budget_transactions
--   20260528052326_add_blocked_task_status.sql<- ALTER TYPE task_status ADD 'blocked'
--
-- DELIBERATELY OMITTED (owned by later migrations, so they apply cleanly on top):
--   * Tables  project_budgets, budget_categories, budget_transactions
--   * Function public.set_updated_at()        (CREATE OR REPLACE in finance mig)
--   * Function public.is_project_director()   (CREATE OR REPLACE in finance mig)
--   * Enum label task_status.'blocked'        (added by add_blocked_task_status)
--   * Column budget_transactions.title        (added by add_transaction_title)
--
-- KNOWN-STALE OBJECTS IN LIVE DB, INTENTIONALLY NOT REPRODUCED (see report):
--   * Function public.hybrid_search()         (references dropped table
--                                              client_documents — would not even
--                                              create cleanly)
--   * storage.objects policies for bucket 'request-attachments' (bucket does not
--                                              exist; orphaned policies)
--
-- NOTE ON ENUM SCHEMA: the user-defined enums live in the `extensions` schema in
-- the live DB (not `public`). This is unusual but reproduced faithfully so that
-- column types and the existing finance/ALTER migrations resolve identically.
-- =====================================================================


-- profiles
CREATE POLICY "Users can view own profile" ON public.profiles
  FOR SELECT USING (auth.uid() = uid);
CREATE POLICY "Directors can view all profiles" ON public.profiles
  FOR SELECT USING (public.is_director(auth.uid()));
CREATE POLICY "Users can update own profile" ON public.profiles
  FOR UPDATE USING (auth.uid() = uid) WITH CHECK (auth.uid() = uid);

-- projects
CREATE POLICY "Users can view their projects" ON public.projects
  FOR SELECT USING (id IN (SELECT private.user_project_ids()));

-- project_members
CREATE POLICY "Users can view project memberships" ON public.project_members
  FOR SELECT USING (project_id IN (SELECT private.user_project_ids()));
CREATE POLICY "Directors can assign members to projects" ON public.project_members
  FOR INSERT WITH CHECK (public.is_director(auth.uid()));
CREATE POLICY "Directors can remove members from projects" ON public.project_members
  FOR DELETE USING (public.is_director(auth.uid()));

-- conversations
CREATE POLICY "Users can view their own conversations" ON public.conversations
  FOR SELECT TO authenticated USING (
    (client_profile_id = public.user_profile_id(auth.uid()))
    OR (director_profile_id = public.user_profile_id(auth.uid()))
  );
CREATE POLICY "Users can create their own conversations" ON public.conversations
  FOR INSERT TO authenticated WITH CHECK (
    (client_profile_id = public.user_profile_id(auth.uid()))

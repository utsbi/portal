  FOR SELECT TO authenticated
  USING (
    public.is_director(auth.uid())
    OR EXISTS (
      SELECT 1 FROM public.file_space_members fsm
      JOIN public.file_spaces fs ON fs.id = fsm.file_space_id
      WHERE fs.department_id = departments.id
        AND fsm.profile_id = public.user_profile_id(auth.uid())
    )
  );


CREATE OR REPLACE FUNCTION public.file_space_can_read(
  check_uid uuid,
  check_space_id bigint
)
RETURNS boolean
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $$
  SELECT public.is_director(check_uid)
    OR EXISTS (
      SELECT 1
      FROM public.file_spaces AS fs
      JOIN public.profiles AS p ON p.uid = check_uid
      LEFT JOIN public.project_members AS pm
        ON pm.project_id = fs.project_id AND pm.profile_id = p.id
      LEFT JOIN public.file_space_members AS fsm
        ON fsm.file_space_id = fs.id AND fsm.profile_id = p.id
      WHERE fs.id = check_space_id
        AND (
          (fs.kind = 'project' AND pm.profile_id IS NOT NULL)
          OR (
            fs.kind = 'department'
            AND fsm.profile_id IS NOT NULL
            AND p.role <> 'client'::extensions.profile_role
          )
        )
    );
$$;

CREATE OR REPLACE FUNCTION public.file_space_can_write(
  check_uid uuid,
  check_space_id bigint
)
RETURNS boolean
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $$
  SELECT public.is_director(check_uid)
    OR EXISTS (
      SELECT 1
      FROM public.file_spaces AS fs
      JOIN public.profiles AS p ON p.uid = check_uid
      JOIN public.file_space_members AS fsm
        ON fsm.file_space_id = fs.id AND fsm.profile_id = p.id
      WHERE fs.id = check_space_id
        AND fs.kind = 'department'
        AND p.role = 'member'::extensions.profile_role
    );
$$;

CREATE OR REPLACE FUNCTION public.file_space_can_manage(
  check_uid uuid,
  check_space_id bigint
)
RETURNS boolean
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $$
  SELECT public.is_director(check_uid);
$$;

-- Resolve both existing project roots and new department roots.
CREATE OR REPLACE FUNCTION public.storage_file_space_id(object_name text)
RETURNS bigint
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $$
  SELECT fs.id
  FROM public.file_spaces AS fs
  WHERE fs.root_prefix = CASE
    WHEN split_part(object_name, '/', 1) = 'department'
      THEN 'department/' || split_part(object_name, '/', 2)
    ELSE split_part(object_name, '/', 1)
  END
  LIMIT 1;
$$;

-- Replace the Files bucket predicates with space-aware predicates while
-- retaining the existing project folder permissions from 20260812000008.
CREATE OR REPLACE FUNCTION public.storage_file_can_read(
  check_uid uuid,
  object_name text
)
RETURNS boolean
LANGUAGE plpgsql
STABLE SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $$
DECLARE
  space_id bigint;
  space_kind text;
  folder record;
  profile_role text;
BEGIN
  space_id := public.storage_file_space_id(object_name);
  IF space_id IS NULL THEN RETURN false; END IF;

  SELECT kind INTO space_kind FROM public.file_spaces WHERE id = space_id;
  IF space_kind = 'department' THEN
    RETURN public.file_space_can_read(check_uid, space_id);
  END IF;

  SELECT access_mode, client_visible, project_id
  INTO folder
  FROM public.storage_file_folder_access(object_name);
  IF folder.project_id IS NULL
    OR NOT public.storage_path_project_member(check_uid, object_name)
  THEN RETURN false; END IF;
  IF public.is_director(check_uid) THEN RETURN true; END IF;

  SELECT role::text INTO profile_role FROM public.profiles WHERE uid = check_uid;
  IF profile_role = 'client' THEN
    RETURN folder.client_visible AND folder.access_mode <> 'restricted';
  END IF;
  RETURN profile_role = 'member'
    AND folder.access_mode IN ('shared', 'member_inbox');
END;
$$;

CREATE OR REPLACE FUNCTION public.storage_file_can_insert(
  check_uid uuid,
  object_name text
)
RETURNS boolean
LANGUAGE plpgsql
STABLE SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $$
DECLARE
  space_id bigint;
  space_kind text;
  folder record;
BEGIN
  space_id := public.storage_file_space_id(object_name);
  IF space_id IS NULL THEN RETURN false; END IF;
  SELECT kind INTO space_kind FROM public.file_spaces WHERE id = space_id;
  IF space_kind = 'department' THEN
    RETURN public.file_space_can_write(check_uid, space_id);
  END IF;

  SELECT access_mode, project_id INTO folder
  FROM public.storage_file_folder_access(object_name);
  RETURN public.is_director(check_uid)
    AND folder.project_id IS NOT NULL
    AND public.storage_path_project_member(check_uid, object_name)
  OR (
    EXISTS (SELECT 1 FROM public.profiles WHERE uid = check_uid AND role = 'member')
    AND public.storage_path_project_member(check_uid, object_name)
    AND folder.access_mode = 'member_inbox'
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.storage_file_can_manage(
  check_uid uuid,
  object_name text
)
RETURNS boolean
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $$
  SELECT CASE
    WHEN public.storage_file_space_id(object_name) IS NULL THEN false
    WHEN EXISTS (
      SELECT 1 FROM public.file_spaces
      WHERE id = public.storage_file_space_id(object_name)
        AND kind = 'department'
    ) THEN public.file_space_can_manage(
      check_uid, public.storage_file_space_id(object_name)
    )
    ELSE public.is_director(check_uid)
      AND public.storage_path_project_member(check_uid, object_name)
  END;
$$;


-- Department-owned file spaces.
--
-- A file has one home: either an existing project space or a persistent
-- department space. Department files are not copied into projects and a link
-- to a project never grants project members access to the file.
--
-- Department object paths use `department/{department_id}/...`.
-- Existing project paths (`{project_id}/...`) remain unchanged.

CREATE TABLE IF NOT EXISTS public.departments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  name text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT departments_slug_check CHECK (slug = lower(slug) AND slug ~ '^[a-z0-9-]+$')
);

CREATE TABLE IF NOT EXISTS public.file_spaces (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('project', 'department')),
  name text NOT NULL,
  project_id bigint REFERENCES public.projects(id) ON DELETE CASCADE,
  department_id bigint REFERENCES public.departments(id) ON DELETE CASCADE,
  root_prefix text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT file_spaces_project_key UNIQUE (project_id),
  CONSTRAINT file_spaces_department_key UNIQUE (department_id),
  CONSTRAINT file_spaces_owner_check CHECK (
    (kind = 'project' AND project_id IS NOT NULL AND department_id IS NULL)
    OR (kind = 'department' AND project_id IS NULL AND department_id IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS file_spaces_kind_idx ON public.file_spaces (kind);

CREATE TABLE IF NOT EXISTS public.file_space_members (
  file_space_id bigint NOT NULL REFERENCES public.file_spaces(id) ON DELETE CASCADE,
  profile_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  membership_source text NOT NULL DEFAULT 'explicit'
    CHECK (membership_source IN ('profile', 'explicit')),
  granted_by bigint REFERENCES public.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (file_space_id, profile_id)
);
CREATE INDEX IF NOT EXISTS file_space_members_profile_idx
  ON public.file_space_members (profile_id, file_space_id);

-- A department file may be related to many projects. This is an association,
-- not an authorization edge. `storage_path` is the full Files bucket object
-- path so it remains stable even if the visible filename is changed elsewhere.
CREATE TABLE IF NOT EXISTS public.department_file_project_links (
  file_space_id bigint NOT NULL REFERENCES public.file_spaces(id) ON DELETE CASCADE,
  storage_path text NOT NULL,
  project_id bigint NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  created_by bigint REFERENCES public.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (file_space_id, storage_path, project_id)
);
CREATE INDEX IF NOT EXISTS department_file_project_links_project_idx
  ON public.department_file_project_links (project_id);

